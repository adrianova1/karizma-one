export function getMasterCategoryTitle(catName: string): string {
  if (!catName) return "شرایط آلفا و پرستیژ";
  const c = catName.trim().toLowerCase();

  // Shit test / شیت تست
  if (c.includes("اهل رابطه") || c.includes("کی هستی") || c.includes("وقتش نیست") || c.includes("دوستت ندارم") || c.includes("شیت") || c.includes("تست") || c.includes("سنجش")) {
    return "شیت‌تست (سنجش عیار)";
  }

  // Push-pull / پوش پول
  if (c.includes("پوش") || c.includes("push") || c.includes("pull") || c.includes("پول") || c.includes("کشش") || c.includes("رانش") || c.includes("دوپهلو") || c.includes("اولین برخورد")) {
    return "پوش-پول (کشش و رانش)";
  }

  // Tongue / Witty / زبون ریزی و حاضرجوابی
  if (c.includes("زبون") || c.includes("حاضر") || c.includes("کنایه") || c.includes("طعنه") || c.includes("متلک") || c.includes("توهین") || c.includes("بی‌احترامی") || c.includes("دندان") || c.includes("سنگین") || c.includes("طنز") || c.includes("شوخی") || c.includes("فان")) {
    return "زبون‌ریزی و حاضرجوابی";
  }

  // Story / Starters / استوری تلنگر و استارترها
  if (c.includes("استوری") || c.includes("تلنگر") || c.includes("ریپلای") || c.includes("شروع") || c.includes("اولین") || c.includes("یخ‌شکن") || c.includes("استارتر") || c.includes("چت")) {
    return "استوری تلنگر و استارترها";
  }

  // Recovery / سردی و مدیریت گفتگو
  if (c.includes("دیر") || c.includes("سین") || c.includes("سرد") || c.includes("بلاک") || c.includes("آنفالو") || c.includes("بی‌محلی") || c.includes("مدیریت")) {
    return "سردی و مدیریت گفتگو";
  }

  // Alpha / پرستیژ و زبان بدن
  if (c.includes("زبان بدن") || c.includes("چشمی") || c.includes("عطر") || c.includes("استایل") || c.includes("قرار") || c.includes("مذاکره") || c.includes("کار") || c.includes("دانشگاه") || c.includes("آلفا") || c.includes("پرستیژ")) {
    return "شرایط آلفا و پرستیژ";
  }

  return "شرایط آلفا و پرستیژ";
}

